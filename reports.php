<?php

require __DIR__ . '/db.php';

$user = require_role('admin', 'super_admin');
$action = $_GET['action'] ?? 'summary';

$period = $_GET['period'] ?? 'daily';
$tz = new DateTimeZone('Asia/Manila');

switch ($period) {
    case 'daily':
        $date = DateTime::createFromFormat('Y-m-d', $_GET['date'] ?? '', $tz) ?: new DateTime('today', $tz);
        $from = $date->format('Y-m-d 00:00:00');
        $to   = $date->format('Y-m-d 23:59:59');
        $label = 'Daily report — ' . $date->format('M j, Y (D)');
        break;

    case 'weekly':
        $date = DateTime::createFromFormat('Y-m-d', $_GET['date'] ?? '', $tz) ?: new DateTime('today', $tz);
        $date->modify(('Sunday' === $date->format('l')) ? 'last sunday' : 'sunday last week'); 
        $from = $date->format('Y-m-d 00:00:00');
        $to   = (clone $date)->modify('+6 days')->format('Y-m-d 23:59:59');
        $label = 'Weekly report — ' . $date->format('M j') . ' to ' . (clone $date)->modify('+6 days')->format('M j, Y');
        break;

    case 'monthly':
        $month = DateTime::createFromFormat('Y-m', $_GET['month'] ?? '', $tz) ?: new DateTime('first day of this month', $tz);
        $from = $month->format('Y-m-01 00:00:00');
        $to   = $month->format('Y-m-t 23:59:59');
        $label = 'Monthly report — ' . $month->format('F Y');
        break;

    case 'custom':
        $f = DateTime::createFromFormat('Y-m-d', $_GET['from'] ?? '', $tz);
        $t = DateTime::createFromFormat('Y-m-d', $_GET['to'] ?? '', $tz);
        if (!$f || !$t) {
            json_out(['success' => false, 'message' => 'Invalid date range.']);
        }
        if ($f > $t) { [$f, $t] = [$t, $f]; }
        $from = $f->format('Y-m-d 00:00:00');
        $to   = $t->format('Y-m-d 23:59:59');
        $label = 'Custom report — ' . $f->format('M j, Y') . ' to ' . $t->format('M j, Y');
        break;

    case 'overall':
    default:
        $period = 'overall';
        $from = '2000-01-01 00:00:00';
        $to   = '2999-12-31 23:59:59';
        $label = 'Overall sales report — all time';
        break;
}

/* voided sales are excluded from every report figure (r4: void is a full reversal) */
$Voided = " AND s.status = 'completed'";

if ($action === 'export') {
    $st = db()->prepare(
        'SELECT s.id, s.receipt_no, s.created_at, u.full_name AS cashier, s.total_amount, s.discount,
                s.payment_method,
                (SELECT GROUP_CONCAT(CONCAT(si.qty, "x ", si.product_name) SEPARATOR "; ")
                   FROM sale_items si WHERE si.sale_id = s.id) AS items
           FROM sales s JOIN users u ON u.id = s.cashier_id
          WHERE s.created_at BETWEEN ? AND ?' . $Voided . '
          ORDER BY s.created_at DESC'
    );
    $st->execute([$from, $to]);

    $fn = 'marinas_hardware_' . $period . '_report_' . date('Ymd_His') . '.csv';
    header('Content-Type: text/csv; charset=utf-8');
    header('Content-Disposition: attachment; filename="' . $fn . '"');
    $out = fopen('php://output', 'w');
    fprintf($out, chr(0xEF) . chr(0xBB) . chr(0xBF)); 
    fputcsv($out, ['Marina\'s Hardware — ' . $label]);
    fputcsv($out, ['Generated by', $user['full_name'], 'on', date('M j, Y g:i A')]);
    fputcsv($out, []);
    fputcsv($out, ['Receipt No', 'Date & Time', 'Cashier', 'Items', 'Discount', 'Total', 'Payment']);
    while ($r = $st->fetch()) {
        fputcsv($out, [
            $r['receipt_no'],
            $r['created_at'],
            $r['cashier'],
            $r['items'],
            $r['discount'],
            $r['total_amount'],
            $r['payment_method'],
        ]);
    }
    fclose($out);
    audit_log($user, 'report_export', 'report', null, 'Exported ' . $label);
    exit;
}

$pdo = db();
$q = static function (string $sql, array $p = []) use ($pdo, $from, $to): array {
    $st = $pdo->prepare(str_replace(['{F}', '{T}'], ['?', '?'], $sql));
    $st->execute([...$p, $from, $to]);
    return $st->fetchAll();
};

$st = $pdo->prepare(
    'SELECT COUNT(*) AS transactions,
            COALESCE(SUM(total_amount), 0) AS revenue,
            COALESCE(SUM(total_cost), 0)   AS cost,
            COALESCE(SUM(discount), 0)     AS discounts,
            COALESCE((SELECT SUM(si.qty) FROM sale_items si JOIN sales s2 ON s2.id = si.sale_id
                       WHERE s2.created_at BETWEEN ? AND ? AND s2.status = "completed"), 0) AS items_sold
       FROM sales s
      WHERE s.created_at BETWEEN ? AND ?' . $Voided
);
$st->execute([$from, $to, $from, $to]);
$k = $st->fetch();

$summary = [
    'label'        => $label,
    'period'       => $period,
    'from'         => $from,
    'to'           => $to,
    'transactions' => (int)$k['transactions'],
    'revenue'      => round((float)$k['revenue'], 2),
    'cost'         => round((float)$k['cost'], 2),
    'profit'       => round((float)$k['revenue'] - (float)$k['cost'], 2),
    'discounts'    => round((float)$k['discounts'], 2),
    'items_sold'   => (int)$k['items_sold'],
    'avg_sale'     => $k['transactions'] > 0 ? round((float)$k['revenue'] / (int)$k['transactions'], 2) : 0,
];

switch ($period) {
    case 'daily': 
        $rows = $q('SELECT HOUR(s.created_at) AS h, SUM(s.total_amount) AS total, SUM(s.total_amount - s.total_cost) AS profit
                      FROM sales s WHERE s.created_at BETWEEN {F} AND {T}' . $Voided . ' GROUP BY h');
        $map = array_column($rows, null, 'h');
        $series = [];
        foreach (range(7, 21) as $h) {
            $series[] = [
                'label'  => date('gA', strtotime("$h:00")),
                'sales'  => round((float)($map[$h]['total'] ?? 0), 2),
                'profit' => round((float)($map[$h]['profit'] ?? 0), 2),
            ];
        }
        break;

    case 'weekly': 
        $rows = $q('SELECT DATE(s.created_at) AS d, SUM(s.total_amount) AS total, SUM(s.total_amount - s.total_cost) AS profit
                      FROM sales s WHERE s.created_at BETWEEN {F} AND {T}' . $Voided . ' GROUP BY d');
        $map = array_column($rows, null, 'd');
        $series = [];
        $cur = new DateTime(substr($from, 0, 10));
        for ($i = 0; $i < 7; $i++) {
            $key = $cur->format('Y-m-d');
            $series[] = [
                'label'  => $cur->format('D (M j)'),
                'sales'  => round((float)($map[$key]['total'] ?? 0), 2),
                'profit' => round((float)($map[$key]['profit'] ?? 0), 2),
            ];
            $cur->modify('+1 day');
        }
        break;

    case 'monthly': 
        $rows = $q('SELECT DATE(s.created_at) AS d, SUM(s.total_amount) AS total, SUM(s.total_amount - s.total_cost) AS profit
                      FROM sales s WHERE s.created_at BETWEEN {F} AND {T}' . $Voided . ' GROUP BY d');
        $map = array_column($rows, null, 'd');
        $series = [];
        $cur = new DateTime(substr($from, 0, 10));
        $end = substr($to, 0, 10);
        while ($cur->format('Y-m-d') <= $end) {
            $key = $cur->format('Y-m-d');
            $series[] = [
                'label'  => $cur->format('M j'),
                'sales'  => round((float)($map[$key]['total'] ?? 0), 2),
                'profit' => round((float)($map[$key]['profit'] ?? 0), 2),
            ];
            $cur->modify('+1 day');
        }
        break;

    case 'custom': 
        $rows = $q('SELECT DATE(s.created_at) AS d, SUM(s.total_amount) AS total, SUM(s.total_amount - s.total_cost) AS profit
                      FROM sales s WHERE s.created_at BETWEEN {F} AND {T}' . $Voided . ' GROUP BY d');
        $map = array_column($rows, null, 'd');
        $series = [];
        $cur = new DateTime(substr($from, 0, 10));
        $end = substr($to, 0, 10);
        $n = 0;
        while ($cur->format('Y-m-d') <= $end && $n++ < 62) {
            $key = $cur->format('Y-m-d');
            $series[] = [
                'label'  => $cur->format('M j'),
                'sales'  => round((float)($map[$key]['total'] ?? 0), 2),
                'profit' => round((float)($map[$key]['profit'] ?? 0), 2),
            ];
            $cur->modify('+1 day');
        }
        break;

    default: 
        $rows = $q('SELECT DATE_FORMAT(s.created_at, "%Y-%m") AS m, SUM(s.total_amount) AS total, SUM(s.total_amount - s.total_cost) AS profit
                      FROM sales s WHERE s.created_at BETWEEN {F} AND {T}' . $Voided . ' GROUP BY m ORDER BY m DESC LIMIT 12');
        $map = array_column($rows, null, 'm');
        $series = [];
        $cur = new DateTime('first day of this month');
        for ($i = 0; $i < 12; $i++) {
            $key = $cur->format('Y-m');
            $series[] = [
                'label'  => $cur->format('M y'),
                'sales'  => round((float)($map[$key]['total'] ?? 0), 2),
                'profit' => round((float)($map[$key]['profit'] ?? 0), 2),
            ];
            $cur->modify('-1 month');
        }
        $series = array_reverse($series);
}

$topProducts = $q(
    'SELECT si.product_name AS name, SUM(si.qty) AS qty, SUM(si.subtotal) AS revenue,
            SUM(si.subtotal - si.unit_cost * si.qty) AS profit
       FROM sale_items si JOIN sales s ON s.id = si.sale_id
      WHERE s.created_at BETWEEN {F} AND {T}' . $Voided . '
      GROUP BY si.product_id, si.product_name
      ORDER BY revenue DESC LIMIT 10'
);
foreach ($topProducts as &$tp) {
    $tp['qty'] = (int)$tp['qty'];
    $tp['revenue'] = round((float)$tp['revenue'], 2);
    $tp['profit'] = round((float)$tp['profit'], 2);
}
unset($tp);

$byCashier = $q(
    'SELECT u.full_name AS name, COUNT(*) AS transactions, SUM(s.total_amount) AS revenue
       FROM sales s JOIN users u ON u.id = s.cashier_id
      WHERE s.created_at BETWEEN {F} AND {T}' . $Voided . '
      GROUP BY s.cashier_id, u.full_name ORDER BY revenue DESC'
);
foreach ($byCashier as &$bc) {
    $bc['transactions'] = (int)$bc['transactions'];
    $bc['revenue'] = round((float)$bc['revenue'], 2);
}
unset($bc);

$byCategory = $q(
    'SELECT c.name, SUM(si.qty) AS qty, SUM(si.subtotal) AS revenue
       FROM sale_items si
       JOIN sales s    ON s.id = si.sale_id
       JOIN products p ON p.id = si.product_id
       JOIN categories c ON c.id = p.category_id
      WHERE s.created_at BETWEEN {F} AND {T}' . $Voided . '
      GROUP BY c.id, c.name ORDER BY revenue DESC'
);
foreach ($byCategory as &$bcg) {
    $bcg['qty'] = (int)$bcg['qty'];
    $bcg['revenue'] = round((float)$bcg['revenue'], 2);
}
unset($bcg);

$recent = $q(
    'SELECT s.id, s.receipt_no, s.created_at, u.full_name AS cashier, s.total_amount, s.payment_method, s.status
       FROM sales s JOIN users u ON u.id = s.cashier_id
      WHERE s.created_at BETWEEN {F} AND {T}
      ORDER BY s.created_at DESC LIMIT 15'
);

json_out([
    'success'    => true,
    'summary'    => $summary,
    'series'     => $series,
    'top_products' => $topProducts,
    'by_cashier' => $byCashier,
    'by_category' => $byCategory,
    'recent'     => $recent,
]);
